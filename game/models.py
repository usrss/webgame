def default_species():
    """Fallback species id so legacy ``Fish.objects.create`` calls stay valid."""
    return (
        FishSpecies.objects.filter(key="goldfish")
        .values_list("pk", flat=True)
        .first()
    )


class Fish(models.Model):
    owner = models.ForeignKey(User, on_delete=models.CASCADE, related_name="fish")
    tank = models.ForeignKey(Tank, on_delete=models.CASCADE, related_name="fish")
    species = models.ForeignKey(
        FishSpecies, on_delete=models.PROTECT, related_name="+", default=default_species
    )
    name = models.CharField(max_length=24)
    xp = models.PositiveIntegerField(default=0)
    level = models.PositiveSmallIntegerField(default=1)
    stage = models.PositiveSmallIntegerField(default=0)
    last_fed_at = models.DateTimeField(null=True, blank=True)
    renamed_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["owner", "tank"], name="one_fish_per_user_per_tank"),
        ]
        ordering = ["tank", "name"]

    def clean(self):
        """Model-level validation: only the fish name length belongs to v1.

        Richer name rules (length limits in context, profanity) arrive in later
        phases, so nothing else is validated here.
        """
        max_length = self._meta.get_field("name").max_length
        if len(self.name) > max_length:
            raise ValidationError(
                {"name": f"Fish name cannot exceed {max_length} characters."}
            )

    def __str__(self) -> str:
        return f"{self.name} (level {self.level}, stage {self.stage})"


