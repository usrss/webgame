"""Data models for the aquarium game (Phase 1).

The canonical model from the phase prompt. Game numbers that are tunable live
in ``settings.GAME_SETTINGS``; the model fields keep the canonical field
lengths.
"""

import secrets

from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.exceptions import ValidationError
from django.core.validators import MaxValueValidator, MinValueValidator
from django.db import IntegrityError, models, transaction

User = get_user_model()

_GAME_SETTINGS = settings.GAME_SETTINGS

# Upper-case letters without the look-alikes ``O`` and ``I``, plus the digits
# without their look-alikes ``0`` and ``1``. 24 + 8 = 32 usable characters.
JOIN_CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"

# How many times ``Tank.save`` tries a fresh join code before giving up.
JOIN_CODE_MAX_ATTEMPTS = 10

# Quiz subjects (Phase 7). ``math`` is generated by code; the rest come from the
# hand-written question bank.
SUBJECTS = [
    ("math", "Math"),
    ("spelling", "Spelling"),
    ("reading", "Reading"),
    ("science", "Science"),
    ("general", "General knowledge"),
]
SUBJECT_KEYS = [key for key, _label in SUBJECTS]
QUIZ_GRADE_MIN = 1
QUIZ_GRADE_MAX = 6


def default_quiz_subjects() -> list[str]:
    """The owner's starting subject list, from ``GAME_SETTINGS``."""
    return list(settings.GAME_SETTINGS["QUIZ_DEFAULT_SUBJECTS"])


def generate_join_code() -> str:
    """Return a cryptographically random join code.

    Uses the :mod:`secrets` module (never :mod:`random`) so codes cannot be
    guessed. The length comes from ``GAME_SETTINGS["JOIN_CODE_LENGTH"]``.
    Uniqueness is enforced by :meth:`Tank.save`, so this function deliberately
    does not touch the database.
    """
    length = _GAME_SETTINGS["JOIN_CODE_LENGTH"]
    return "".join(secrets.choice(JOIN_CODE_ALPHABET) for _ in range(length))


class Tank(models.Model):
    name = models.CharField(max_length=40)
    owner = models.ForeignKey(User, on_delete=models.CASCADE, related_name="owned_tanks")
    join_code = models.CharField(max_length=6, unique=True, default=generate_join_code)
    capacity = models.PositiveSmallIntegerField(
        default=_GAME_SETTINGS["DEFAULT_TANK_CAPACITY"]
    )
    # Quiz configuration, chosen by the tank owner (Phase 7).
    quiz_grade = models.PositiveSmallIntegerField(
        default=_GAME_SETTINGS["QUIZ_DEFAULT_GRADE"],
        validators=[MinValueValidator(QUIZ_GRADE_MIN), MaxValueValidator(QUIZ_GRADE_MAX)],
    )
    quiz_subjects = models.JSONField(default=default_quiz_subjects)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
        verbose_name_plural = "tanks"

    def __str__(self) -> str:
        return f"{self.name} ({self.join_code})"

    def clean(self):
        """Validate the quiz grade and subject list (Phase 7)."""
        errors = {}
        if not QUIZ_GRADE_MIN <= (self.quiz_grade or 0) <= QUIZ_GRADE_MAX:
            errors["quiz_grade"] = "Grade must be between 1 and 6."
        subjects = self.quiz_subjects
        if not isinstance(subjects, list) or not subjects:
            errors["quiz_subjects"] = "Pick at least one subject."
        else:
            unknown = [value for value in subjects if value not in SUBJECT_KEYS]
            if unknown:
                errors["quiz_subjects"] = f"Unknown subject(s): {', '.join(map(str, unknown))}."
        if errors:
            raise ValidationError(errors)

    def save(self, *args, **kwargs):
        """Insert the tank, retrying with a fresh join code on collision.

        The retry loop lives here (not in :func:`generate_join_code`) so the
        generator stays pure. Each attempt runs in a savepoint: a ``UNIQUE``
        violation on ``join_code`` is caught, a new code is generated and the
        insert is retried, up to ``JOIN_CODE_MAX_ATTEMPTS`` times. Any other
        integrity error is re-raised untouched. Updates never touch the code.
        """
        if self.pk is not None:
            return super().save(*args, **kwargs)

        last_error = None
        for _ in range(JOIN_CODE_MAX_ATTEMPTS):
            if not self.join_code:
                self.join_code = generate_join_code()
            try:
                with transaction.atomic():
                    super().save(*args, **kwargs)
                return
            except IntegrityError as exc:
                # Only swallow the error if it really was a join-code clash.
                if Tank.objects.filter(join_code=self.join_code).exists():
                    last_error = exc
                    self.join_code = ""
                    continue
                raise

        raise RuntimeError(
            "Could not generate a unique join code after "
            f"{JOIN_CODE_MAX_ATTEMPTS} attempts"
        ) from last_error


class EvolutionStage(models.Model):
    stage_number = models.PositiveSmallIntegerField(unique=True)
    name = models.CharField(max_length=30)
    min_level = models.PositiveSmallIntegerField()
    sprite_key = models.CharField(max_length=30)

    class Meta:
        ordering = ["stage_number"]

    def __str__(self) -> str:
        return f"Stage {self.stage_number}: {self.name}"


class Fish(models.Model):
    owner = models.ForeignKey(User, on_delete=models.CASCADE, related_name="fish")
    tank = models.ForeignKey(Tank, on_delete=models.CASCADE, related_name="fish")
    name = models.CharField(max_length=24)
    xp = models.PositiveIntegerField(default=0)
    level = models.PositiveSmallIntegerField(default=1)
    stage = models.PositiveSmallIntegerField(default=0)
    last_fed_at = models.DateTimeField(null=True, blank=True)
    renamed_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["owner", "tank"], name="one_fish_per_user_per_tank"),
        ]
        ordering = ["tank", "name"]

    def clean(self):
        """Model-level validation: only the fish name length belongs to v1.

        Richer name rules (length limits in context, profanity) arrive in later
        phases, so nothing else is validated here.
        """
        max_length = self._meta.get_field("name").max_length
        if len(self.name) > max_length:
            raise ValidationError(
                {"name": f"Fish name cannot exceed {max_length} characters."}
            )

    def __str__(self) -> str:
        return f"{self.name} (level {self.level}, stage {self.stage})"


class TankBan(models.Model):
    """A user kicked from a tank; they cannot rejoin until unbanned."""

    tank = models.ForeignKey(Tank, on_delete=models.CASCADE, related_name="bans")
    user = models.ForeignKey(User, on_delete=models.CASCADE)
    banned_by = models.ForeignKey(
        User, on_delete=models.SET_NULL, null=True, related_name="+"
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=["tank", "user"], name="one_ban_per_user_per_tank"),
        ]
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"{self.user} banned from {self.tank}"


class Question(models.Model):
    """One hand-written bank question (math questions are generated, not stored)."""

    subject = models.CharField(max_length=20, choices=SUBJECTS)
    grade = models.PositiveSmallIntegerField(
        validators=[MinValueValidator(QUIZ_GRADE_MIN), MaxValueValidator(QUIZ_GRADE_MAX)]
    )
    prompt = models.CharField(max_length=200)
    choices = models.JSONField()
    correct_index = models.PositiveSmallIntegerField()
    explanation = models.CharField(max_length=200, blank=True)
    active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["subject", "grade", "id"]

    def clean(self):
        """A question needs 3-4 distinct, non-empty choices and a valid answer."""
        errors = {}
        choices = self.choices
        if (
            not isinstance(choices, list)
            or not 3 <= len(choices) <= 4
            or any(not isinstance(choice, str) or not choice.strip() for choice in choices)
        ):
            errors["choices"] = "Provide 3 or 4 non-empty answer choices."
        else:
            if len(set(choices)) != len(choices):
                errors["choices"] = "Answer choices must be distinct."
            if any(len(choice) > 100 for choice in choices):
                errors["choices"] = "Answer choices cannot exceed 100 characters."
        if not isinstance(self.correct_index, int) or not 0 <= self.correct_index <= 3:
            errors["correct_index"] = "The correct answer must be one of the choices."
        elif isinstance(choices, list) and self.correct_index >= len(choices):
            errors["correct_index"] = "The correct answer must be one of the choices."
        if errors:
            raise ValidationError(errors)

    def __str__(self) -> str:
        return f"{self.get_subject_display()} (grade {self.grade}): {self.prompt}"


class QuestionAttempt(models.Model):
    """One issued question.

    Always a snapshot of what the player was shown, so generated math and bank
    questions behave identically. ``correct_index`` is server-side only and is
    never serialized before the attempt is answered.
    """

    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name="+")
    fish = models.ForeignKey(Fish, on_delete=models.CASCADE, related_name="attempts")
    question = models.ForeignKey(
        Question, null=True, blank=True, on_delete=models.SET_NULL
    )
    subject = models.CharField(max_length=20)
    grade = models.PositiveSmallIntegerField()
    prompt = models.CharField(max_length=200)
    choices = models.JSONField()
    correct_index = models.PositiveSmallIntegerField()
    explanation = models.CharField(max_length=200, blank=True)
    issued_at = models.DateTimeField()
    answered_at = models.DateTimeField(null=True, blank=True)
    selected_index = models.PositiveSmallIntegerField(null=True, blank=True)
    correct = models.BooleanField(null=True, blank=True)

    class Meta:
        indexes = [
            models.Index(fields=["fish", "answered_at"]),
            models.Index(fields=["user", "issued_at"]),
        ]
        ordering = ["-issued_at"]

    def __str__(self) -> str:
        state = "unanswered" if self.answered_at is None else "answered"
        return f"Attempt {self.pk} ({self.subject}, {state})"


class FishReport(models.Model):
    """One player's report about a fish name, resolved by a moderator."""

    REASON_NAME = "name"
    REASON_OTHER = "other"
    REASON_CHOICES = [
        (REASON_NAME, "Offensive name"),
        (REASON_OTHER, "Other"),
    ]

    fish = models.ForeignKey(Fish, on_delete=models.CASCADE, related_name="reports")
    reporter = models.ForeignKey(User, on_delete=models.CASCADE, related_name="+")
    reason = models.CharField(max_length=20, choices=REASON_CHOICES)
    note = models.CharField(max_length=200, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    resolved = models.BooleanField(default=False)

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["fish", "reporter"], name="one_report_per_user_per_fish"
            ),
        ]
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"Report on {self.fish} by {self.reporter}"
