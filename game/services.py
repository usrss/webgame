"""Game-rule service layer (Phase 1).

Views and model ``save()`` call into this module; nothing else mutates ``xp``,
``level``, ``stage`` or ``last_fed_at``. All tunable numbers come from
``GAME_SETTINGS`` in ``settings.py`` - there are no game numbers here.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from datetime import datetime, timedelta

from django.conf import settings
from django.core.exceptions import PermissionDenied, ValidationError
from django.db import transaction
from django.utils import timezone

from .models import (
    JOIN_CODE_MAX_ATTEMPTS,
    SLOT_KEYS,
    Accessory,
    EvolutionStage,
    Fish,
    FishReport,
    FishSpecies,
    PlayerProfile,
    PearlTransaction,
    Tank,
    TankBan,
    UserAccessory,
    FishEquipment,
    generate_join_code,
)
from .validators import validate_display_name

logger = logging.getLogger(__name__)

_XP_PER_FEED = settings.GAME_SETTINGS["XP_PER_FEED"]
_FEED_COOLDOWN_SECONDS = settings.GAME_SETTINGS["FEED_COOLDOWN_SECONDS"]
_XP_PER_LEVEL_STEP = settings.GAME_SETTINGS["XP_PER_LEVEL_STEP"]
_MAX_LEVEL = settings.GAME_SETTINGS["MAX_LEVEL"]
_HUNGER_FULL_SECONDS = settings.GAME_SETTINGS["HUNGER_FULL_SECONDS"]


class JoinError(Exception):
    """Base class for every reason a join attempt can fail."""


class InvalidJoinCode(JoinError):
    """No tank has the requested join code."""


class TankFull(JoinError):
    """The tank already has as many fish as its capacity allows."""


class AlreadyInTank(JoinError):
    """The user already owns a fish in that tank."""


class Banned(JoinError):
    """The user was kicked from this tank and cannot rejoin."""


class CannotRenameYet(Exception):
    """The fish was renamed too recently; the cooldown has not passed."""

    def __init__(self, seconds_remaining: int) -> None:
        self.seconds_remaining = seconds_remaining
        super().__init__(
            f"This fish can be renamed again in {seconds_remaining} seconds"
        )


class InvalidSpecies(Exception):
    """The requested species does not exist or is not active."""


class NotForSale(Exception):
    """Only active shop accessories can be bought with pearls."""


class AlreadyOwned(Exception):
    """The user already owns this accessory."""


class NotEnoughPearls(Exception):
    """The purchase (or deduction) would make the balance negative."""

    def __init__(self, missing: int) -> None:
        self.missing = missing
        super().__init__(f"{missing} more pearl(s) needed")


class AccessoryNotFound(Exception):
    """No such accessory, or it is not active."""


class NotOwned(Exception):
    """The user does not own the accessory they tried to equip."""


class InvalidSlot(Exception):
    """The accessory does not belong in the requested slot."""


class AlreadyReported(Exception):
    """This user already reported this fish."""


class FeedOnCooldown(Exception):
    """Raised when a fish cannot be fed because the cooldown has not passed."""

    def __init__(self, seconds_remaining: int) -> None:
        self.seconds_remaining = seconds_remaining
        super().__init__(f"Fish cannot be fed for {seconds_remaining} more seconds")


@dataclass
class FeedResult:
    """Outcome of a successful feed, safe to hand straight to a view/JSON."""

    fish: Fish
    xp_gained: int
    leveled_up: bool
    levels_gained: int
    evolved: bool
    old_stage: int
    new_stage: int
    cooldown_seconds: int
    pearls_gained: int = 0
    gifts: list = field(default_factory=list)  # newly granted Accessory rows


def get_species(key: str | None) -> FishSpecies:
    """Resolve an active species key; ``None``/empty means goldfish."""
    key = (key or "goldfish").strip().lower()
    species = FishSpecies.objects.filter(key=key, active=True).first()
    if species is None:
        raise InvalidSpecies("Pick one of the available fish species.")
    return species


def create_tank(
    owner, tank_name: str, fish_name: str, species: str | None = "goldfish"
) -> tuple[Tank, Fish]:
    """Create a tank and the owner's first fish in one transaction.

    Both names go through :func:`validate_display_name`, so callers may pass raw
    form input. The tank gets its own join code (generated by ``Tank.save``) and
    the settings-driven capacity; the fish starts at level 1, stage 0 with no
    XP. Returns ``(tank, fish)``.
    """
    tank_name = validate_display_name(
        tank_name, max_length=Tank._meta.get_field("name").max_length, field_label="Tank name"
    )
    fish_name = validate_display_name(
        fish_name, max_length=Fish._meta.get_field("name").max_length, field_label="Fish name"
    )
    species_row = get_species(species)

    with transaction.atomic():
        tank = Tank.objects.create(
            owner=owner,
            name=tank_name,
            capacity=settings.GAME_SETTINGS["DEFAULT_TANK_CAPACITY"],
        )
        fish = Fish.objects.create(
            owner=owner,
            tank=tank,
            species=species_row,
            name=fish_name,
            level=1,
            stage=0,
        )
    return tank, fish


def join_tank(
    user, code: str, fish_name: str, species: str | None = "goldfish"
) -> tuple[Tank, Fish]:
    """Join an existing tank by join code, creating the user's fish.

    The code is normalized (trimmed, upper-cased). Everything happens inside a
    transaction that locks the tank row with ``select_for_update`` and counts
    the fish **inside that lock**, so two players racing for the last slot cannot
    both be admitted. Works on MySQL/InnoDB and PostgreSQL; the lock only has an
    effect inside the transaction, which this function owns.

    Raises :class:`InvalidJoinCode`, :class:`TankFull` or
    :class:`AlreadyInTank`; propagates ``ValidationError`` for a bad fish name.
    """
    normalized = (code or "").strip().upper()
    fish_name = validate_display_name(
        fish_name, max_length=Fish._meta.get_field("name").max_length, field_label="Fish name"
    )
    species_row = get_species(species)

    with transaction.atomic():
        tank = (
            Tank.objects.select_for_update()
            .filter(join_code=normalized)
            .first()
        )
        if tank is None:
            raise InvalidJoinCode("No tank matches that join code.")

        if TankBan.objects.filter(tank=tank, user=user).exists():
            raise Banned("You were removed from that tank.")

        if Fish.objects.filter(tank=tank, owner=user).exists():
            raise AlreadyInTank("You already have a fish in that tank.")

        if tank.fish.count() >= tank.capacity:
            raise TankFull("That tank is full.")

        fish = Fish.objects.create(
            owner=user,
            tank=tank,
            species=species_row,
            name=fish_name,
            level=1,
            stage=0,
        )
    return tank, fish


def get_membership(user, tank_id) -> Fish | None:
    """Return the user's fish in the tank, or ``None`` when they aren't a member.

    This is the single authorization check every tank view must use: never
    trust a tank id from the client on its own.
    """
    return (
        Fish.objects.select_related("tank")
        .filter(owner=user, tank_id=tank_id)
        .first()
    )


def _require_owner(tank: Tank, actor) -> None:
    """Authorization lives here so no view (or crafted request) can skip it."""
    if tank.owner_id != getattr(actor, "pk", None):
        raise PermissionDenied("Only the tank owner can do that.")


def _assign_unique_join_code(tank: Tank) -> Tank:
    """Give *tank* a fresh, unused join code (caller holds the row lock)."""
    for _ in range(JOIN_CODE_MAX_ATTEMPTS):
        candidate = generate_join_code()
        if not Tank.objects.filter(join_code=candidate).exists():
            tank.join_code = candidate
            tank.save(update_fields=["join_code"])
            return tank
    raise RuntimeError(
        "Could not generate a unique join code after "
        f"{JOIN_CODE_MAX_ATTEMPTS} attempts"
    )


def regenerate_join_code(tank: Tank, actor) -> Tank:
    """Issue a new join code, invalidating the old one immediately (owner only)."""
    _require_owner(tank, actor)
    with transaction.atomic():
        locked = Tank.objects.select_for_update().get(pk=tank.pk)
        _assign_unique_join_code(locked)
    logger.info("Tank %s: join code regenerated by %s", tank.pk, actor.pk)
    return locked


def kick_player(tank: Tank, actor, fish_id: int) -> None:
    """Delete a member's fish and ban them from the tank (owner only).

    The owner cannot kick themselves. The ban is created first so a failure
    rolls both changes back together.
    """
    _require_owner(tank, actor)
    with transaction.atomic():
        fish = Fish.objects.select_for_update().filter(pk=fish_id, tank=tank).first()
        if fish is None:
            raise Fish.DoesNotExist("Fish not found in this tank")
        if fish.owner_id == tank.owner_id:
            raise PermissionDenied("The owner cannot kick themselves.")
        TankBan.objects.get_or_create(tank=tank, user=fish.owner, defaults={"banned_by": actor})
        fish.delete()
    logger.info("Tank %s: kicked fish %s (user %s) by %s", tank.pk, fish_id, fish.owner_id, actor.pk)


def unban_player(tank: Tank, actor, user_id: int) -> int:
    """Remove a ban so the user may rejoin (owner only). Returns rows removed."""
    _require_owner(tank, actor)
    deleted, _details = TankBan.objects.filter(tank=tank, user_id=user_id).delete()
    logger.info("Tank %s: unbanned user %s by %s", tank.pk, user_id, actor.pk)
    return deleted


def rename_fish(tank: Tank, actor, fish_id: int, new_name: str) -> Fish:
    """Owner moderation: rename any fish in their tank (full name rules apply)."""
    _require_owner(tank, actor)
    cleaned = validate_display_name(
        new_name, max_length=Fish._meta.get_field("name").max_length, field_label="Fish name"
    )
    fish = Fish.objects.filter(pk=fish_id, tank=tank).first()
    if fish is None:
        raise Fish.DoesNotExist("Fish not found in this tank")
    fish.name = cleaned
    fish.save(update_fields=["name"])
    logger.info("Tank %s: renamed fish %s by %s", tank.pk, fish_id, actor.pk)
    return fish


def delete_tank(tank: Tank, actor, confirm_name: str) -> None:
    """Delete a tank and everything in it, with the exact name as confirmation."""
    _require_owner(tank, actor)
    if (confirm_name or "").strip() != tank.name:
        raise ValidationError("Type the tank name exactly to confirm deletion.")
    tank.delete()
    logger.info("Tank %s: deleted by %s", tank.pk, actor.pk)


def leave_tank(user, tank: Tank) -> None:
    """A member removes their own fish. The owner must delete the tank instead."""
    if tank.owner_id == getattr(user, "pk", None):
        raise PermissionDenied("Owners cannot leave their own tank; delete it instead.")
    deleted, _details = Fish.objects.filter(tank=tank, owner=user).delete()
    if not deleted:
        raise Fish.DoesNotExist("You are not a member of this tank")
    logger.info("Tank %s: user %s left", tank.pk, user.pk)


def rename_own_fish(user, tank: Tank, new_name: str, now=None) -> Fish:
    """Rename your own fish, limited to once per ``RENAME_COOLDOWN_SECONDS``."""
    cleaned = validate_display_name(
        new_name, max_length=Fish._meta.get_field("name").max_length, field_label="Fish name"
    )
    now = now or timezone.now()
    cooldown = settings.GAME_SETTINGS["RENAME_COOLDOWN_SECONDS"]

    with transaction.atomic():
        fish = Fish.objects.select_for_update().filter(tank=tank, owner=user).first()
        if fish is None:
            raise Fish.DoesNotExist("You are not a member of this tank")
        if fish.renamed_at is not None:
            ready_at = fish.renamed_at + timedelta(seconds=cooldown)
            remaining = (ready_at - now).total_seconds()
            if remaining > 0:
                raise CannotRenameYet(int(remaining) + 1)
        fish.name = cleaned
        fish.renamed_at = now
        fish.save(update_fields=["name", "renamed_at"])
    logger.info("Tank %s: user %s renamed their fish", tank.pk, user.pk)
    return fish


def report_fish(fish: Fish, reporter, reason: str = FishReport.REASON_NAME, note: str = "") -> FishReport:
    """Report a tank-mate's fish once. Members only; never your own fish."""
    if not Fish.objects.filter(tank=fish.tank, owner=reporter).exists():
        raise PermissionDenied("You are not a member of this tank.")
    if fish.owner_id == getattr(reporter, "pk", None):
        raise PermissionDenied("You cannot report your own fish.")

    valid_reasons = {choice for choice, _label in FishReport.REASON_CHOICES}
    if reason not in valid_reasons:
        raise ValidationError("Unknown report reason.")
    note = (note or "").strip()
    if len(note) > FishReport._meta.get_field("note").max_length:
        raise ValidationError("Report note is too long.")

    report, created = FishReport.objects.get_or_create(
        fish=fish, reporter=reporter, defaults={"reason": reason, "note": note}
    )
    if not created:
        raise AlreadyReported("You already reported this fish.")
    logger.info("Fish %s reported by %s (%s)", fish.pk, reporter.pk, reason)
    return report


